/**
 * The case record: one surgery for one patient on one date at one site of service,
 * created only from a signed surgical order.
 *
 * Identifiers are plain string aliases so they interoperate with `@scheduler/tenancy`
 * (RAH-9) once it lands; swap them for its exported types at integration.
 */

export type PracticeId = string;
export type LocationId = string;
export type FacilityId = string;
export type SurgeonId = string;
export type UserId = string;
export type CaseId = string;
export type CaseSeriesId = string;
export type OrderId = string;
export type AuthorizationId = string;
export type ReadinessItemId = string;
export type PartyId = string;
export type CommunicationId = string;
export type ChangeEventId = string;

/** ISO 8601 timestamp, e.g. `2026-11-25T14:00:00.000Z`. */
export type IsoDateTime = string;
/** ISO 8601 calendar date, e.g. `2026-12-02`. */
export type IsoDate = string;

export const CASE_STATES = [
  'ordered',
  'intake_done',
  'auth_pending',
  'booked',
  'ready',
  'confirmed',
  'surgery_done',
  'closed',
  'blocked',
  'rescheduling',
  'cancelled',
] as const;
export type CaseState = (typeof CASE_STATES)[number];

/** insured, self-pay, or mixed (some procedures insured, some self-pay such as cosmetic). */
export type CaseType = 'insured' | 'self_pay' | 'mixed';

export type SiteOfService =
  | { kind: 'office_procedure_room'; locationId: LocationId; roomName?: string }
  | { kind: 'facility'; facilityId: FacilityId };

export type Actor =
  | { kind: 'human'; userId: UserId; role: 'scheduler' | 'surgeon' | 'practice_admin' }
  | { kind: 'agent'; agentId: string }
  | { kind: 'system'; process: string };

export type HumanActor = Extract<Actor, { kind: 'human' }>;

export interface SurgicalOrder {
  id: OrderId;
  practiceId: PracticeId;
  surgeonId: SurgeonId;
  /** Present only once the surgeon has signed. A case cannot be created from an unsigned order. */
  signature?: { signedBy: SurgeonId; signedAt: IsoDateTime };
  /** A signed urgent order approves an urgent add-on (ADR-0007). */
  urgent: boolean;
  cptCodes: string[];
  diagnosisCodes: string[];
}

export interface Procedure {
  cptCode: string;
  description: string;
  laterality?: 'left' | 'right' | 'bilateral';
  /** Who pays for this procedure. In a mixed case some are insured and some self-pay. */
  billing: 'insured' | 'self_pay';
}

export interface Team {
  surgeonId: SurgeonId;
  assistantIds: string[];
  anesthesia?: 'local' | 'mac' | 'general';
}

export interface Slot {
  start: IsoDateTime;
  end: IsoDateTime;
  roomName?: string;
}

export type AuthorizationStatus = 'pending' | 'approved' | 'denied';

/** One authorization can cover several cases in the same series. */
export interface Authorization {
  id: AuthorizationId;
  practiceId: PracticeId;
  payerName: string;
  status: AuthorizationStatus;
  authNumber?: string;
  cptCodes: string[];
  validFrom: IsoDate;
  validTo: IsoDate;
  /** Cases this authorization covers, explicitly or through a series. */
  coverage: { caseIds: CaseId[]; caseSeriesId?: CaseSeriesId };
}

export type ReadinessItemKind =
  | 'eligibility_check'
  | 'prior_authorization'
  | 'payer_notification_post_surgery'
  | 'retro_authorization'
  | 'self_pay_quote'
  | 'financial_consent'
  | 'deposit'
  // Clinical items are generated by the readiness rules (RAH-60); the model only carries them.
  | 'history_and_physical'
  | 'surgical_consent'
  | 'pre_op_labs'
  | 'imaging'
  | 'medical_clearance';

export type ReadinessCategory = 'insurance' | 'self_pay' | 'clinical';

export interface ReadinessItem {
  id: ReadinessItemId;
  kind: ReadinessItemKind;
  category: ReadinessCategory;
  /** pre_op items gate Ready; post_op items are tracked after surgery (urgent add-ons). */
  phase: 'pre_op' | 'post_op';
  required: boolean;
  status: 'open' | 'complete';
  completedAt?: IsoDateTime;
  /** When set, the item is valid only through this date (inclusive). */
  validUntil?: IsoDate;
  authorizationId?: AuthorizationId;
  /** External reference, e.g. the processor's deposit confirmation ID. */
  reference?: string;
}

export interface Party {
  id: PartyId;
  role: 'patient' | 'surgeon' | 'scheduler' | 'facility_contact' | 'payer' | 'care_team';
  displayName: string;
}

export interface Communication {
  id: CommunicationId;
  at: IsoDateTime;
  partyId: PartyId;
  channel: 'phone' | 'sms' | 'email' | 'fax' | 'portal';
  direction: 'inbound' | 'outbound';
  summary: string;
}

export type ChangeEventKind =
  | 'created'
  | 'state_changed'
  | 'case_type_changed'
  | 'authorization_linked'
  | 'readiness_item_completed'
  | 'rescheduled';

export interface ChangeEvent {
  id: ChangeEventId;
  caseId: CaseId;
  at: IsoDateTime;
  actor: Actor;
  kind: ChangeEventKind;
  fromState?: CaseState;
  toState?: CaseState;
  fromCaseType?: CaseType;
  toCaseType?: CaseType;
  reason?: string;
  details?: Record<string, string | number | boolean>;
}

export interface CaseSeries {
  id: CaseSeriesId;
  practiceId: PracticeId;
  label: string;
  caseIds: CaseId[];
}

export interface Case {
  id: CaseId;
  practiceId: PracticeId;
  order: SurgicalOrder;
  caseType: CaseType;
  seriesId?: CaseSeriesId;
  urgentAddOn: boolean;
  state: CaseState;
  /** Set while Blocked: the state to return to. */
  blockedFrom?: CaseState;
  blockedReason?: string;
  site: SiteOfService;
  surgeryDate: IsoDate;
  procedures: Procedure[];
  team: Team;
  slot?: Slot;
  authorizationIds: AuthorizationId[];
  readinessItems: ReadinessItem[];
  parties: Party[];
  communications: Communication[];
  /** Full history, oldest first. Never truncated, including across cancel and reopen. */
  history: ChangeEvent[];
  /** Set the first time the case reaches Booked; never reset, so a case is billed once. */
  billableAt?: IsoDateTime;
  cancelledAt?: IsoDateTime;
  surgeryCompletedAt?: IsoDateTime;
  firstPostOpVisitAt?: IsoDateTime;
  closedAt?: IsoDateTime;
  /** Closing starts the 90-day PHI deletion clock (ADR-0005). */
  phiDeletionDueAt?: IsoDateTime;
}
